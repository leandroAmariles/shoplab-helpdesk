package com.shoplab.helpdesk.chat.application.usecase;

import com.shoplab.helpdesk.chat.application.port.out.SmallTalkModelPort;
import com.shoplab.helpdesk.chat.config.SmallTalkProperties;
import org.springframework.stereotype.Component;
import reactor.core.publisher.Flux;

/**
 * The small-talk path of the chat (LAB-114): whether a message takes it and the answer it gets. With the path turned
 * off by configuration no message takes it and the chat behaves as before the path existed.
 */
@Component
public class SmallTalk {

    private final SmallTalkClassifier classifier;
    private final SmallTalkProperties properties;
    private final SmallTalkModelPort model;

    public SmallTalk(SmallTalkClassifier classifier, SmallTalkProperties properties, SmallTalkModelPort model) {
        this.classifier = classifier;
        this.properties = properties;
        this.model = model;
    }

    /** Whether the message is answered as small talk: the path is enabled and the message is only a courtesy. */
    public boolean handles(String message) {
        return properties.enabled() && classifier.isSmallTalk(message);
    }

    /**
     * Whether a stored question was only a courtesy, to keep it out of the text the knowledge base is searched with.
     * Without the path enabled no question is filtered, so the search is the one of before LAB-114.
     */
    public boolean isCourtesy(String question) {
        return properties.enabled() && classifier.isSmallTalk(question);
    }

    /** The answer to a courtesy, generated by the model without history, fragments or tools. */
    public Flux<String> reply(String message) {
        return model.streamReply(message);
    }
}
