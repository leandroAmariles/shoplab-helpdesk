MAX_ROWS_SHOWN = 5
FULL_SCALE_MIN_ORDERS = 1_000  # below this the data is a test sample (CI fixtures), not Olist
FIGURE_DPI = 100  # moderate resolution keeps the saved notebook small (research D-16)
BAR_COLOR = "#4C78A8"
LATE_COLOR = "#E45756"
HISTOGRAM_BINS = 40


def show_table(frame: pd.DataFrame, max_rows: int = MAX_ROWS_SHOWN) -> pd.DataFrame:
    """A sample safe to print: at most ``max_rows`` rows and never an identifier column (FR-024).

    Olist identifiers are anonymised hashes, but the dataset is not versioned (CC BY-NC-SA), so the saved notebook
    must not dump it. Aggregates are not affected: they have no ``*_id`` columns.
    """
    visible = [name for name in frame.columns if not str(name).endswith("_id")]
    return frame.loc[:, visible].head(max_rows)


def format_pct(fraction: float) -> str:
    """A fraction in [0, 1] as a percentage with two decimals; missing values as a dash."""
    if fraction is None or (isinstance(fraction, float) and math.isnan(fraction)):
        return "—"
    return f"{fraction * 100:.2f} %"


def format_int(value: int) -> str:
    return f"{int(value):,}"


def data_scale(order_count: int) -> str:
    """``full`` for the real dataset, ``sample`` for the few rows the CI fixtures load."""
    return "full" if order_count >= FULL_SCALE_MIN_ORDERS else "sample"


def _range_cell(value: object) -> str:
    """A range value for reading: dates as YYYY-MM-DD, numbers with two decimals, missing as a dash."""
    if value is None or value is pd.NaT or (isinstance(value, float) and math.isnan(value)):
        return "—"
    if isinstance(value, pd.Timestamp):
        return value.strftime("%Y-%m-%d")
    return f"{float(value):.2f}"


def profile_view(profile: TableProfile) -> pd.DataFrame:
    """The column profile of a table as a compact, Spanish-headed table."""
    frame = profile.to_frame()
    view = pd.DataFrame(
        {
            "columna": frame["column"],
            "tipo": frame["dtype"],
            "nulos": frame["null_count"],
            "% nulos": frame["null_pct"].round(2),
            "nulos inesperados": frame["unexpected_null_count"],
        }
    )
    for source, target in (("min", "mín"), ("p01", "p01"), ("p50", "p50"), ("p99", "p99"), ("max", "máx")):
        view[target] = frame[source].map(_range_cell)
    view["implausibles"] = frame["implausible_count"]
    return view


def table_headline(profile: TableProfile) -> str:
    """The numbers of a table in one line, generated by code so the prose around it cannot contradict them."""
    return (
        f"{profile.table}: {profile.rows:,} filas · duplicados por clave: {profile.key_duplicates:,} · "
        f"duplicados de fila completa: {profile.row_duplicates:,}"
    )


def summary_view(summary: pd.DataFrame) -> pd.DataFrame:
    """A delay summary (by state or category) with Spanish headers and two decimals."""
    return pd.DataFrame(
        {
            "grupo": summary["group"],
            "pedidos": summary["orders"],
            "retraso medio (días)": summary["mean_delay_days"].astype("float64").round(2),
            "% con retraso": summary["delayed_pct"].astype("float64").round(2),
            "puntuación media": summary["mean_review_score"].astype("float64").round(2),
        }
    ).reset_index(drop=True)


# -- figures ---------------------------------------------------------------------------------------------------------
# They use matplotlib's object API (no pyplot state), so they work the same in a notebook, in CI and in tests.


def _new_figure(columns: int, width: float, height: float = 4.0) -> tuple[Figure, np.ndarray]:
    figure = Figure(figsize=(width, height), dpi=FIGURE_DPI, layout="tight")
    return figure, np.atleast_1d(figure.subplots(1, columns))


def plot_delivery_times(frame: pd.DataFrame) -> Figure | None:
    """Real vs estimated time, the difference between them and the share early / on the day / late."""
    analysed = frame[frame["analyzed"]]
    if analysed.empty:
        return None
    figure, (times, delay, shares) = _new_figure(3, 15.0)

    upper = float(np.percentile(analysed[["actual_days", "estimated_days"]].to_numpy(), 99))
    times.hist(analysed["actual_days"], bins=HISTOGRAM_BINS, range=(0, upper), alpha=0.7, color=BAR_COLOR, label="real")
    times.hist(
        analysed["estimated_days"], bins=HISTOGRAM_BINS, range=(0, upper), alpha=0.5, color="#F58518", label="estimado"
    )
    times.set(title="Tiempo de entrega (hasta el percentil 99)", xlabel="días desde la compra", ylabel="pedidos")
    times.legend()

    low, high = np.percentile(analysed["delay_days"], [1, 99])
    delay.hist(analysed["delay_days"], bins=HISTOGRAM_BINS, range=(float(low), float(high)), color=BAR_COLOR)
    delay.axvline(0, color=LATE_COLOR, linestyle="--")
    delay.set(title="Real − estimado (positivo = tarde)", xlabel="días", ylabel="pedidos")

    gap = analysed["delay_days"]
    percentages = [(gap < 0).mean() * 100, (gap == 0).mean() * 100, (gap > 0).mean() * 100]
    bars = shares.bar(
        ["antes", "el mismo día", "después"], percentages, color=[BAR_COLOR, BAR_COLOR, LATE_COLOR]
    )
    shares.bar_label(bars, fmt="%.1f %%")
    shares.set(title="Frente a la fecha estimada", ylabel="% de pedidos")
    return figure


def plot_delay_ranking(ranking: pd.DataFrame, title: str, top_n: int = 10) -> Figure | None:
    """The groups with the highest share of delayed orders, the worst on top."""
    if ranking.empty:
        return None
    figure, (axis,) = _new_figure(1, 8.0, height=0.45 * min(len(ranking), top_n) + 1.5)
    top = ranking.head(top_n).iloc[::-1]  # barh draws the first row at the bottom
    bars = axis.barh(top["group"], top["delayed_pct"], color=LATE_COLOR)
    labels = [f"{pct:.1f} % ({orders:,} pedidos)" for pct, orders in zip(top["delayed_pct"], top["orders"], strict=True)]
    axis.bar_label(bars, labels=labels)
    axis.set(title=title, xlabel="% de pedidos entregados con retraso")
    axis.margins(x=0.25)
    return figure


def plot_review_scores(distribution: pd.Series, by_bucket: pd.DataFrame) -> Figure | None:
    """How many reviews have each score, and the mean score by delay tier."""
    if int(distribution.sum()) == 0:
        return None
    figure, (scores, buckets) = _new_figure(2, 11.0)
    bars = scores.bar([str(score) for score in distribution.index], distribution.to_numpy(), color=BAR_COLOR)
    scores.bar_label(bars, labels=[f"{value:,}" for value in distribution.to_numpy()])
    scores.set(title="Puntuación de las reseñas", xlabel="puntuación", ylabel="reseñas")
    if by_bucket.empty or by_bucket["mean_score"].isna().all():
        buckets.text(0.5, 0.5, "sin pedidos con reseña", ha="center", va="center", transform=buckets.transAxes)
    else:
        means = by_bucket["mean_score"].fillna(0)
        bars = buckets.bar(by_bucket["bucket"], means, color=[BAR_COLOR, "#F58518", LATE_COLOR])
        buckets.bar_label(bars, labels=[f"{value:.2f}" for value in means])
        buckets.set_ylim(0, 5.5)
    buckets.set(title="Puntuación media según el retraso", ylabel="puntuación media")
    return figure


_AREA_LABELS = {"quality": "calidad", "values": "valores", "delivery": "entregas"}


def findings_view(found: list[Finding]) -> pd.DataFrame:
    """The discrepancies with their action, as a table for reading (section 12 of the notebook)."""
    return pd.DataFrame(
        {
            "área": [_AREA_LABELS[item.area] for item in found],
            "tipo": [item.kind for item in found],
            "sujeto": [item.subject for item in found],
            "cantidad": [item.count for item in found],
            "%": [round(item.share * 100, 2) for item in found],
            "impacto": [item.impact for item in found],
            "destino": [item.target for item in found],
            "acción": [item.action for item in found],
        }
    )


# -- JSON summary (contracts/summary-format.md) ----------------------------------------------------------------------

SCHEMA_VERSION = 1
SUMMARY_TABLE_COUNT = 8
_IDENTIFIER = re.compile(r"[0-9a-f]{32}")  # the shape of an Olist id; it must never reach a saved file


def _number(value: Any) -> float | None:
    """A float rounded to four decimals for the summary; missing values become null."""
    if value is None or (isinstance(value, float) and math.isnan(value)) or pd.isna(value):
        return None
    return round(float(value), 4)


def _describe_or_none(stats: dict[str, float] | None) -> dict[str, float | None] | None:
    return None if stats is None else {name: _number(value) for name, value in stats.items()}


def _value_rows(items: list[categorical.ValueFrequency]) -> list[dict[str, Any]]:
    rows = []
    for item in items:
        row: dict[str, Any] = {
            "value": item.value,
            "count": item.count,
            "share": _number(item.share),
            "declared_by_policy": item.declared_by_policy,
            "mentioned_in": list(item.mentioned_in),
        }
        if item.covered_by_order_tool is not None:
            row["covered_by_order_tool"] = item.covered_by_order_tool
        rows.append(row)
    return rows


def build_summary(
    tables: dict[str, pd.DataFrame],
    *,
    profiles: dict[str, TableProfile],
    frequencies: dict[str, list[categorical.ValueFrequency]],
    absent: categorical.AbsentValues,
    exclusions: delivery.ExclusionCounts,
    stats: delivery.TimeStatistics,
    distribution: pd.Series,
    by_bucket: pd.DataFrame,
    found: list[Finding],
    generated_at: str | None = None,
) -> dict[str, Any]:
    """The machine-readable summary of the last run: aggregates only, no identifiers and no rows of data."""
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_at": generated_at or datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "data_scale": data_scale(len(tables["orders.orders"])),
        "tables": [
            {
                "table": profile.table,
                "rows": profile.rows,
                "key_duplicates": profile.key_duplicates,
                "row_duplicates": profile.row_duplicates,
                "columns_with_unexpected_nulls": [c.name for c in profile.columns if c.unexpected_null_count],
            }
            for profile in profiles.values()
        ],
        "values": {
            "payment_type": _value_rows(frequencies["payment_type"]),
            "order_status": _value_rows(frequencies["order_status"]),
            "absent_from_data": {
                "payment_type": list(absent.payment_type),
                "order_status": list(absent.order_status_policy),
            },
        },
        "delivery": {
            "analyzed_orders": stats.analyzed_orders,
            "excluded": {
                "no_delivery_date": exclusions.no_delivery_date,
                "delivered_before_purchase": exclusions.delivered_before_purchase,
                "estimated_before_purchase": exclusions.estimated_before_purchase,
                "delivered_without_date": exclusions.delivered_without_date,
            },
            "actual_days": _describe_or_none(stats.actual_days),
            "estimated_days": _describe_or_none(stats.estimated_days),
            "early_pct": _number(stats.early_pct),
            "same_day_pct": _number(stats.same_day_pct),
            "late_pct": _number(stats.late_pct),
        },
        "reviews": {
            "count": int(distribution.sum()),
            "score_distribution": {str(score): int(count) for score, count in distribution.items()},
            "mean_score_by_delay_bucket": {
                bucket: _number(mean) for bucket, mean in zip(by_bucket["bucket"], by_bucket["mean_score"], strict=True)
            },
        },
        "findings": [
            {
                "kind": item.kind,
                "subject": item.subject,
                "area": item.area,
                "count": item.count,
                "share": _number(item.share),
                "target": item.target,
                "action": item.action,
            }
            for item in found
        ],
    }


def validate_summary(summary: dict[str, Any]) -> None:
    """Enforces the contract: the eight tables, an action on every finding and no identifier anywhere."""
    if not isinstance(summary.get("schema_version"), int):
        raise ValueError("El resumen necesita un `schema_version` entero.")
    if len(summary.get("tables", [])) != SUMMARY_TABLE_COUNT:
        raise ValueError(f"El resumen debe tener exactamente {SUMMARY_TABLE_COUNT} tablas.")
    for finding in summary.get("findings", []):
        if not finding.get("action") or not finding.get("target"):
            raise ValueError(f"El hallazgo {finding.get('kind')}:{finding.get('subject')} no tiene action ni target.")
    if _IDENTIFIER.search(json.dumps(summary, ensure_ascii=False)):
        raise ValueError("El resumen contiene algo con forma de identificador de Olist (32 caracteres hexadecimales).")


def write_summary(summary: dict[str, Any], path: Path) -> None:
    validate_summary(summary)
    path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def read_summary(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))
